#!/usr/bin/env node
/**
 * Builds the daily aura seed migration and the review doc from the content
 * files in supabase/content/daily-aura/season-<n>/<animal>.json.
 *
 * Each content file is a JSON array of [message, do_text, dont_text]. The
 * array position is the day_index (1-based).
 *
 * Usage:
 *   node scripts/build-daily-aura-seed.js            # season 1
 *   node scripts/build-daily-aura-seed.js 2 <file>   # season 2, custom migration file name
 *   node scripts/build-daily-aura-seed.js --check    # validate only
 *
 * Fails (exit 1) on: wrong count, too-long texts, repeats, banned topics, emojis.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ANIMALS = [
  'bear', 'cat', 'deer', 'dolphin', 'eagle', 'elephant', 'fox', 'lion',
  'otter', 'owl', 'parrot', 'peacock', 'snake', 'unicorn', 'wolf',
];
const LIMITS = { message: 110, do: 40, dont: 40 };
const EXPECTED_PER_ANIMAL = 60;
const REVIEW_COUNT = 5;

// Topics the content must stay away from (health/medical, politics, religion, substances).
const BANNED = [
  /\b(doctor|medic\w*|medication|pill|therapy|therapist|diet|calorie|weight loss|workout|hydrat\w*|vitamin|sick|illness|disease|anxiety disorder|depress\w*)\b/i,
  /\b(politic\w*|election|vote|government|president|left-wing|right-wing)\b/i,
  /\b(god|gods|pray\w*|prayer|church|mosque|temple|bible|quran|religio\w*|karma|blessed|holy|sin)\b/i,
  /\b(alcohol|drunk|wine|beer|vodka|shots?|weed|drugs?|cigarette|smok\w*|hangover)\b/i,
];
const EMOJI = /\p{Extended_Pictographic}/u;

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const positional = args.filter(arg => !arg.startsWith('--'));
const season = Number(positional[0] ?? 1);
const migrationName = positional[1] ?? '20261117090100_daily_aura_season1_seed.sql';

const contentDir = path.join(ROOT, 'supabase', 'content', 'daily-aura', `season-${season}`);
const errors = [];
const seen = new Map();

function normalize(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

function sqlString(text) {
  return `'${text.replace(/'/g, "''")}'`;
}

const content = {};
for (const animal of ANIMALS) {
  const file = path.join(contentDir, `${animal}.json`);
  if (!fs.existsSync(file)) {
    errors.push(`${animal}: missing ${path.relative(ROOT, file)}`);
    continue;
  }
  const rows = JSON.parse(fs.readFileSync(file, 'utf8'));
  content[animal] = rows;
  if (rows.length !== EXPECTED_PER_ANIMAL) {
    errors.push(`${animal}: ${rows.length} rows, expected ${EXPECTED_PER_ANIMAL}`);
  }
  rows.forEach((row, index) => {
    const where = `${animal} #${index + 1}`;
    if (!Array.isArray(row) || row.length !== 3 || row.some(value => typeof value !== 'string' || !value.trim())) {
      errors.push(`${where}: must be [message, do, dont] with non-empty strings`);
      return;
    }
    const [message, doText, dontText] = row;
    [['message', message], ['do', doText], ['dont', dontText]].forEach(([field, text]) => {
      if (text.length > LIMITS[field]) errors.push(`${where}: ${field} is ${text.length} chars (max ${LIMITS[field]}): ${text}`);
      if (EMOJI.test(text)) errors.push(`${where}: ${field} contains an emoji: ${text}`);
      BANNED.forEach(pattern => {
        const match = text.match(pattern);
        if (match) errors.push(`${where}: ${field} mentions "${match[0]}": ${text}`);
      });
    });
    const key = normalize(message);
    if (seen.has(key)) errors.push(`${where}: message repeats ${seen.get(key)}: ${message}`);
    else seen.set(key, where);
  });
}

if (errors.length > 0) {
  console.error(`Found ${errors.length} problem(s):\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

const total = Object.values(content).reduce((sum, rows) => sum + rows.length, 0);
console.log(`OK: ${total} messages for season ${season} (${ANIMALS.length} animals).`);
if (checkOnly) process.exit(0);

// Seed migration: look up aura_id by name, idempotent.
const values = [];
for (const animal of ANIMALS) {
  content[animal].forEach(([message, doText, dontText], index) => {
    values.push(`  (${sqlString(animal)}, ${index + 1}, ${sqlString(message)}, ${sqlString(doText)}, ${sqlString(dontText)})`);
  });
}
const sql = `-- Daily aura messages, season ${season}: ${total} rows (${EXPECTED_PER_ANIMAL} per animal).
-- GENERATED by scripts/build-daily-aura-seed.js from supabase/content/daily-aura/season-${season}/.
-- Edit the JSON files and re-run the script; don't edit this file by hand.
--
-- aura_id is looked up by animal name (case-insensitive). Idempotent: re-running
-- skips rows that already exist for (aura_id, season, day_index).

begin;

insert into public.daily_aura_messages (aura_id, season, day_index, message, do_text, dont_text)
select a.id, ${season}, v.day_index, v.message, v.do_text, v.dont_text
from (values
${values.join(',\n')}
) as v (animal, day_index, message, do_text, dont_text)
join public.animal_auras a on lower(btrim(a.name)) = v.animal
on conflict (aura_id, season, day_index) do nothing;

-- Every animal must be found, or the seed silently skips its rows.
do $$
declare
  v_missing text;
begin
  select string_agg(v.animal, ', ') into v_missing
  from unnest(array[${ANIMALS.map(sqlString).join(', ')}]) as v (animal)
  where not exists (select 1 from public.animal_auras a where lower(btrim(a.name)) = v.animal);
  if v_missing is not null then
    raise exception 'daily aura seed: animals not found in animal_auras: %', v_missing;
  end if;
end $$;

commit;
`;
const migrationPath = path.join(ROOT, 'supabase', 'migrations', migrationName);
fs.writeFileSync(migrationPath, sql);
console.log(`Wrote ${path.relative(ROOT, migrationPath)}`);

// Review doc: first messages of each animal.
const capitalize = text => text.charAt(0).toUpperCase() + text.slice(1);
let review = `# Daily aura review: season ${season}\n\n`;
review += `The first ${REVIEW_COUNT} of ${EXPECTED_PER_ANIMAL} messages for each animal, in the order users see them (day 1 = #1).\n`;
review += `Source: \`supabase/content/daily-aura/season-${season}/\`. Generated by \`scripts/build-daily-aura-seed.js\`.\n`;
for (const animal of ANIMALS) {
  review += `\n## ${capitalize(animal)}\n\n| # | Message | Do | Don't |\n|---|---|---|---|\n`;
  content[animal].slice(0, REVIEW_COUNT).forEach(([message, doText, dontText], index) => {
    const cell = text => text.replace(/\|/g, '\\|');
    review += `| ${index + 1} | ${cell(message)} | ${cell(doText)} | ${cell(dontText)} |\n`;
  });
}
const reviewPath = path.join(ROOT, 'docs', season === 1 ? 'daily-aura-review.md' : `daily-aura-review-season-${season}.md`);
fs.writeFileSync(reviewPath, review);
console.log(`Wrote ${path.relative(ROOT, reviewPath)}`);
